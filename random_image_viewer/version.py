"""Application version, derived from git tags (single source of truth).

Releases are marked with annotated SemVer tags (``v1.2.0``). Every commit
after a tag gets a unique PEP 440 version automatically - no file to edit:

    v1.2.0 tag, clean checkout        -> 1.2.0
    3 commits after v1.2.0            -> 1.2.0+3.gabc1234
    ... plus uncommitted changes      -> 1.2.0+3.gabc1234.dirty

Running from a git checkout asks ``git describe``, so the number follows every
commit. A frozen build cannot ask git, so the PyInstaller spec stamps the
version into ``_version.py`` (generated, git-ignored) via ``write_version_file``.

Kept free of Qt and package imports: the build spec loads it by file path.
"""

import os
import re
import subprocess
import sys
from functools import lru_cache

_PKG_DIR = os.path.dirname(os.path.abspath(__file__))
_REPO_DIR = os.path.dirname(_PKG_DIR)
VERSION_FILE = os.path.join(_PKG_DIR, "_version.py")
UNKNOWN = "0.0.0+unknown"

_DESCRIBE_RE = re.compile(
    r"^v?(?P<base>\d+(?:\.\d+)*)-(?P<distance>\d+)-g(?P<sha>[0-9a-f]+)"
    r"(?P<dirty>-dirty)?$")


def version_from_git(repo_dir=_REPO_DIR):
    """PEP 440 version from ``git describe``, or None outside a checkout."""
    if not os.path.exists(os.path.join(repo_dir, ".git")):
        return None
    cmd = ["git", "describe", "--tags", "--long", "--dirty", "--match", "v[0-9]*"]
    try:
        out = subprocess.run(
            cmd, cwd=repo_dir, capture_output=True, text=True, timeout=5,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    m = _DESCRIBE_RE.match(out)
    if not m:
        return None  # no release tag yet, or git unavailable
    version = m["base"]
    local = []
    if int(m["distance"]):
        local += [m["distance"], "g" + m["sha"]]
    if m["dirty"]:
        local.append("dirty")
    return version + ("+" + ".".join(local) if local else "")


def _version_from_file():
    try:
        from random_image_viewer._version import __version__
        return __version__
    except ImportError:
        return None


@lru_cache(maxsize=None)
def get_version():
    """The running app's version. Asks git (~50 ms) on first call when running
    from source, so call it after the window is up, not during startup."""
    if not getattr(sys, "frozen", False):
        v = version_from_git()
        if v:
            return v
    return _version_from_file() or UNKNOWN


def numeric_version(version):
    """4-part ``(major, minor, patch, commits)`` tuple for the Windows exe
    version resource, e.g. ``1.2.0+3.gabc1234`` -> ``(1, 2, 0, 3)``."""
    base, _, local = version.partition("+")
    parts = [int(p) for p in re.findall(r"\d+", base)[:3]]
    parts += [0] * (3 - len(parts))
    distance = local.split(".")[0] if local else "0"
    parts.append(int(distance) if distance.isdigit() else 0)
    return tuple(parts)


def write_version_file(version):
    with open(VERSION_FILE, "w", encoding="utf-8") as f:
        f.write("# Generated by the build (random_image_viewer/version.py) - do not edit.\n")
        f.write(f"__version__ = {version!r}\n")


if __name__ == "__main__":
    print(get_version())
